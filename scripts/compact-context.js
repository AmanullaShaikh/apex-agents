#!/usr/bin/env node

import fs from 'fs';
import path from 'path';

export function compactSourceCode(code) {
  const lines = code.split('\n');
  const compacted = [];
  let inClass = false;

  for (let line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    // Preserve interfaces, type aliases, and import/export declarations
    if (
      trimmed.startsWith('export type') || 
      trimmed.startsWith('export interface') ||
      trimmed.startsWith('type ') || 
      trimmed.startsWith('interface ') ||
      trimmed.startsWith('import ') ||
      trimmed.startsWith('export *') ||
      trimmed.startsWith('//') ||
      trimmed.startsWith('/*') ||
      trimmed.startsWith('*')
    ) {
      compacted.push(line);
      continue;
    }

    // Preserve class headers
    if (/^(export\s+)?(default\s+)?(abstract\s+)?class\s+[a-zA-Z0-9_$]+/.test(trimmed)) {
      compacted.push(line);
      inClass = true;
      continue;
    }

    // Preserve class closing brace
    if (inClass && trimmed === '}') {
      compacted.push(line);
      inClass = false;
      continue;
    }

    // Detect function / method signatures
    const isFunctionHeader = 
      /^(export\s+)?(default\s+)?(async\s+)?function\b/.test(trimmed) ||
      /^(export\s+)?const\s+[a-zA-Z0-9_$]+\s*=\s*(async\s*)?\([^)]*\)\s*(:\s*[^=]+)?\s*=>/.test(trimmed) ||
      /^(public|private|protected|static|async|\s)*[a-zA-Z0-9_$]+\([^)]*\)\s*(:\s*[^{]+)?\s*\{/.test(trimmed);

    if (isFunctionHeader && trimmed.includes('{')) {
      // Extract signature up to the opening brace
      const sig = line.slice(0, line.indexOf('{') + 1);
      compacted.push(sig + ' /* stripped */ }');
      continue;
    }

    // If it's a top-level export or variable, preserve it
    if (trimmed.startsWith('export const') || trimmed.startsWith('export let') || trimmed.startsWith('export default')) {
      if (trimmed.length < 120) {
        compacted.push(line);
      }
    }
  }

  return compacted.join('\n');
}

function runContextCompactor(projectDir) {
  console.log(`\x1b[36m\x1b[1m[Apex-Agents Compactor] Compacting codebase context for LLM window...\x1b[0m\n`);

  const srcDir = path.join(projectDir, 'src');
  const targetDir = fs.existsSync(srcDir) ? srcDir : projectDir;

  const files = getAllSourceFiles(targetDir);
  let originalChars = 0;
  let outputMarkdown = `# Codebase Compact Context Skeleton\nGenerated by Apex Agents Context Compactor\n\n`;

  for (const f of files) {
    const content = fs.readFileSync(f, 'utf-8');
    originalChars += content.length;
    const relPath = path.relative(projectDir, f);
    const compacted = compactSourceCode(content);

    outputMarkdown += `## File: \`${relPath}\`\n\`\`\`typescript\n${compacted}\n\`\`\`\n\n`;
  }

  const compactedChars = outputMarkdown.length;
  const originalTokensEst = Math.round(originalChars / 4);
  const compactedTokensEst = Math.round(compactedChars / 4);
  const savingsPct = (((originalChars - compactedChars) / originalChars) * 100).toFixed(1);

  const outputPath = path.join(projectDir, 'APEX_CONTEXT.md');
  fs.writeFileSync(outputPath, outputMarkdown);

  console.log(`\x1b[32m✓ Skeleton written to:\x1b[0m \x1b[36m${outputPath}\x1b[0m`);
  console.log(`  • Original Size  : \x1b[33m~${originalTokensEst.toLocaleString()} tokens\x1b[0m (${(originalChars / 1024).toFixed(1)} KB)`);
  console.log(`  • Compacted Size : \x1b[32m~${compactedTokensEst.toLocaleString()} tokens\x1b[0m (${(compactedChars / 1024).toFixed(1)} KB)`);
  console.log(`  • \x1b[1mToken Reduction: \x1b[32m${savingsPct}% Saved!\x1b[0m\n`);
  console.log(`\x1b[90mYou can now inject APEX_CONTEXT.md directly into your AI prompt with zero context bloat.\x1b[0m\n`);
}

function getAllSourceFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  for (const entry of entries) {
    if (['node_modules', '.git', 'dist', 'build', '.next', '.agents', '.worktrees'].includes(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      getAllSourceFiles(fullPath, acc);
    } else if (/\.(ts|tsx|js|jsx)$/.test(entry.name) && !entry.name.endsWith('.d.ts')) {
      acc.push(fullPath);
    }
  }
  return acc;
}

export { compactSourceCode as compactJavaScript, runContextCompactor };

if (process.argv[1] && process.argv[1].endsWith('compact-context.js')) {
  const target = process.argv[2] || process.cwd();
  runContextCompactor(target);
}

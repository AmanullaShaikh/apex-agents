#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import { parse } from '@babel/parser';
import * as t from '@babel/traverse';
import * as g from '@babel/generator';

const traverse = t.default?.default || t.default;
const generate = g.default?.default || g.default;

const c = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  cyan: '\x1b[36m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  gray: '\x1b[90m'
};

/**
 * Production-Grade AST Token Compactor using Babel.
 * Preserves exports, types, interfaces, and function signatures.
 * Strips all internal function bodies down to {} for 80-90% token reduction.
 */
export function compactSourceCode(code) {
  if (!code || !code.trim()) return '';

  try {
    const ast = parse(code, {
      sourceType: 'module',
      plugins: [
        'typescript',
        'jsx',
        'classProperties',
        'decorators-legacy',
        'dynamicImport',
        'exportDefaultFrom',
        'exportNamespaceFrom',
        'topLevelAwait'
      ]
    });

    traverse(ast, {
      Function(path) {
        if (path.node.body && path.node.body.type === 'BlockStatement') {
          path.node.body = {
            type: 'BlockStatement',
            body: [],
            directives: []
          };
        }
      }
    });

    const output = generate(ast, { retainLines: false, compact: false }, code);
    return output.code;
  } catch (err) {
    // Graceful fallback for non-JS/TS or malformed WIP files
    return fallbackCompact(code);
  }
}

function fallbackCompact(code) {
  const lines = code.split('\n');
  const compacted = [];
  let inClass = false;

  for (const line of lines) {
    const trimmed = line.trim();
    if (!trimmed) continue;

    if (
      trimmed.startsWith('import ') ||
      trimmed.startsWith('export *') ||
      trimmed.startsWith('export type ') ||
      trimmed.startsWith('type ') ||
      trimmed.startsWith('export interface ') ||
      trimmed.startsWith('interface ') ||
      trimmed.startsWith('export enum ') ||
      trimmed.startsWith('enum ') ||
      trimmed.startsWith('//') ||
      trimmed.startsWith('/*') ||
      trimmed.startsWith('*')
    ) {
      compacted.push(line);
      continue;
    }

    if (/^(export\s+)?(default\s+)?(abstract\s+)?class\s+[a-zA-Z0-9_$]+/.test(trimmed)) {
      compacted.push(line);
      inClass = true;
      continue;
    }

    if (inClass && trimmed === '}') {
      compacted.push(line);
      inClass = false;
      continue;
    }

    const isFunctionHeader =
      /^(export\s+)?(default\s+)?(async\s+)?function\b/.test(trimmed) ||
      /^(export\s+)?const\s+[a-zA-Z0-9_$]+\s*=\s*(async\s*)?\([^)]*\)\s*(:\s*[^=]+)?\s*=>/.test(trimmed) ||
      /^(public|private|protected|static|async|\s)*[a-zA-Z0-9_$]+\([^)]*\)\s*(:\s*[^{]+)?\s*\{/.test(trimmed);

    if (isFunctionHeader && trimmed.includes('{')) {
      const sig = line.slice(0, line.indexOf('{') + 1);
      compacted.push(sig + ' /* stripped */ }');
      continue;
    }

    if (trimmed.startsWith('export const') || trimmed.startsWith('export let') || trimmed.startsWith('export default')) {
      if (trimmed.length < 120) {
        compacted.push(line);
      }
    }
  }

  return compacted.join('\n');
}

export function runContextCompactor(projectDir) {
  console.log(`\n${c.cyan}${c.bold}═════ APEX AGENTS: BABEL AST CONTEXT COMPACTOR ═════${c.reset}`);
  console.log(`Extracting type-safe code skeletons from: ${c.cyan}${projectDir}${c.reset}...\n`);

  const files = getAllSourceFiles(projectDir);

  if (files.length === 0) {
    console.log(`${c.yellow}No JavaScript / TypeScript files found to compact.${c.reset}\n`);
    return;
  }

  let originalChars = 0;
  let compactedChars = 0;
  let outputMarkdown = `# Project Codebase Skeleton (Generated by Apex Agents AST Compactor)\n\n`;
  outputMarkdown += `This document contains the structural type and function signatures of the codebase with implementation bodies stripped to save 85%+ context window tokens.\n\n`;

  let processedCount = 0;
  for (const file of files) {
    const relPath = path.relative(projectDir, file).replace(/\\/g, '/');
    try {
      const rawContent = fs.readFileSync(file, 'utf-8');
      originalChars += rawContent.length;

      const skeleton = compactSourceCode(rawContent);
      compactedChars += skeleton.length;

      const ext = path.extname(file).replace('.', '');
      outputMarkdown += `## File: \`${relPath}\`\n`;
      outputMarkdown += `\`\`\`${ext === 'ts' || ext === 'tsx' ? 'typescript' : 'javascript'}\n`;
      outputMarkdown += skeleton + '\n';
      outputMarkdown += `\`\`\`\n\n`;
      processedCount++;
    } catch (err) {
      // safely skip
    }
  }

  const originalTokensEst = Math.ceil(originalChars / 3.8);
  const compactedTokensEst = Math.ceil(compactedChars / 3.8);
  const savingsPct = (((originalTokensEst - compactedTokensEst) / (originalTokensEst || 1)) * 100).toFixed(1);

  const outputPath = path.join(projectDir, 'APEX_CONTEXT.md');
  fs.writeFileSync(outputPath, outputMarkdown);

  console.log(`  ${c.green}✓${c.reset} Processed ${c.cyan}${processedCount}${c.reset} files.`);
  console.log(`  ${c.green}✓${c.reset} Skeleton written to: ${c.cyan}${outputPath}${c.reset}`);
  console.log(`  • Original Context : ${c.yellow}~${originalTokensEst.toLocaleString()} tokens${c.reset} (${(originalChars / 1024).toFixed(1)} KB)`);
  console.log(`  • Compacted Context: ${c.green}~${compactedTokensEst.toLocaleString()} tokens${c.reset} (${(compactedChars / 1024).toFixed(1)} KB)`);
  console.log(`  • ${c.bold}Context Reduction : ${c.green}${c.bold}${savingsPct}% Saved!${c.reset}\n`);
  console.log(`${c.gray}Inject APEX_CONTEXT.md directly into your AI prompt for full codebase awareness without context bloat.${c.reset}\n`);
}

function getAllSourceFiles(dir, acc = []) {
  if (!fs.existsSync(dir)) return acc;
  const entries = fs.readdirSync(dir, { withFileTypes: true });

  const IGNORED = new Set(['node_modules', '.git', 'dist', 'build', '.next', '.agents', '.worktrees', 'coverage']);

  for (const entry of entries) {
    if (IGNORED.has(entry.name)) continue;
    const fullPath = path.join(dir, entry.name);

    if (entry.isDirectory()) {
      getAllSourceFiles(fullPath, acc);
    } else if (/\.(ts|tsx|js|jsx|mjs|cjs)$/.test(entry.name) && !entry.name.endsWith('.d.ts')) {
      acc.push(fullPath);
    }
  }
  return acc;
}

export { compactSourceCode as compactJavaScript };

// CLI Execution
if (process.argv[1] && process.argv[1].endsWith('compact-context.js')) {
  const target = process.argv[2] || process.cwd();
  runContextCompactor(target);
}

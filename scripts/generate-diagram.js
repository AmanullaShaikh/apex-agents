#!/usr/bin/env node

import fs from 'fs';
import path from 'path';
import os from 'os';
import { spawn } from 'child_process';
import { buildDependencyGraph } from './dependency-graph.js';

const c = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  cyan: '\x1b[36m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  gray: '\x1b[90m'
};

export function generateArchitectureDiagram(rootDir = process.cwd(), openInBrowser = false) {
  console.log(`\n${c.cyan}${c.bold}═════ APEX AGENTS: EDITORIAL ARCHITECTURE GENERATOR ═════${c.reset}`);
  console.log(`Analyzing repository architecture in: ${c.cyan}${rootDir}${c.reset}...\n`);

  const { modulesCount, graph, externalDeps, cycles } = buildDependencyGraph(rootDir);

  // Group modules by directory
  const directoryGroups = new Map();
  for (const mod of graph.keys()) {
    const dir = path.dirname(mod);
    const topDir = dir === '.' ? 'root' : dir.split('/')[0];
    if (!directoryGroups.has(topDir)) {
      directoryGroups.set(topDir, []);
    }
    directoryGroups.get(topDir).push(mod);
  }

  // Read package.json if present
  let pkgName = path.basename(rootDir);
  let pkgVersion = '1.0.0';
  const pkgPath = path.join(rootDir, 'package.json');
  if (fs.existsSync(pkgPath)) {
    try {
      const pkg = JSON.parse(fs.readFileSync(pkgPath, 'utf-8'));
      if (pkg.name) pkgName = pkg.name;
      if (pkg.version) pkgVersion = pkg.version;
    } catch {}
  }

  // Generate self-contained HTML/SVG
  const html = `<!DOCTYPE html>
<html lang="en">
<head>
  <meta charset="UTF-8">
  <meta name="viewport" content="width=device-width, initial-scale=1.0">
  <title>${pkgName} - Architecture Diagram</title>
  <style>
    :root {
      --bg: #090a0f;
      --card-bg: #11141d;
      --border: rgba(255, 255, 255, 0.08);
      --accent: #5e6ad2;
      --text-main: #f0f3f8;
      --text-muted: #8a93a5;
      --font-mono: ui-monospace, SFMono-Regular, "SF Mono", Menlo, Consolas, monospace;
    }
    * { box-sizing: border-box; margin: 0; padding: 0; }
    body {
      background: var(--bg);
      color: var(--text-main);
      font-family: -apple-system, BlinkMacSystemFont, "Segoe UI", Roboto, sans-serif;
      padding: 40px;
      line-height: 1.5;
    }
    .header {
      margin-bottom: 32px;
      border-bottom: 1px solid var(--border);
      padding-bottom: 24px;
      display: flex;
      justify-content: space-between;
      align-items: center;
    }
    .title { font-size: 24px; font-weight: 700; display: flex; align-items: center; gap: 12px; }
    .badge {
      background: rgba(94, 106, 210, 0.2);
      color: #8f9bff;
      padding: 4px 10px;
      border-radius: 6px;
      font-size: 13px;
      font-weight: 600;
      font-family: var(--font-mono);
    }
    .stats-bar {
      display: flex;
      gap: 24px;
      margin-bottom: 32px;
    }
    .stat-card {
      background: var(--card-bg);
      border: 1px solid var(--border);
      padding: 16px 20px;
      border-radius: 8px;
      min-width: 140px;
    }
    .stat-label { font-size: 12px; color: var(--text-muted); text-transform: uppercase; font-weight: 600; }
    .stat-val { font-size: 22px; font-weight: 700; color: #fff; margin-top: 4px; font-family: var(--font-mono); }
    .grid {
      display: grid;
      grid-template-columns: repeat(auto-fit, minmax(320px, 1fr));
      gap: 24px;
    }
    .tier-box {
      background: var(--card-bg);
      border: 1px solid var(--border);
      border-radius: 10px;
      padding: 20px;
    }
    .tier-header {
      font-size: 15px;
      font-weight: 700;
      color: #b8c4da;
      margin-bottom: 14px;
      padding-bottom: 10px;
      border-bottom: 1px solid var(--border);
      display: flex;
      justify-content: space-between;
    }
    .module-item {
      font-family: var(--font-mono);
      font-size: 12px;
      padding: 8px 12px;
      background: rgba(255, 255, 255, 0.03);
      border-radius: 6px;
      margin-bottom: 8px;
      display: flex;
      justify-content: space-between;
      border: 1px solid transparent;
    }
    .module-item:hover {
      border-color: var(--accent);
      background: rgba(94, 106, 210, 0.08);
    }
    .dep-count { color: var(--text-muted); font-size: 11px; }
  </style>
</head>
<body>
  <div class="header">
    <div class="title">
      <span>📐 ${pkgName}</span>
      <span class="badge">v${pkgVersion}</span>
      <span class="badge" style="background: rgba(34, 197, 94, 0.15); color: #4ade80;">AST Verified</span>
    </div>
    <div style="color: var(--text-muted); font-size: 13px;">Generated by Apex Agents Architecture Engine</div>
  </div>

  <div class="stats-bar">
    <div class="stat-card">
      <div class="stat-label">Modules</div>
      <div class="stat-val">${modulesCount}</div>
    </div>
    <div class="stat-card">
      <div class="stat-label">External Deps</div>
      <div class="stat-val">${externalDeps.length}</div>
    </div>
    <div class="stat-card">
      <div class="stat-label">Circular Cycles</div>
      <div class="stat-val" style="color: ${cycles.length > 0 ? '#ef4444' : '#22c55e'};">${cycles.length}</div>
    </div>
  </div>

  <div class="grid">
    ${Array.from(directoryGroups.entries()).map(([dir, files]) => `
      <div class="tier-box">
        <div class="tier-header">
          <span>📁 /${dir}</span>
          <span style="color: var(--text-muted); font-size: 12px;">${files.length} files</span>
        </div>
        ${files.map(f => {
          const deps = graph.get(f) || new Set();
          return `
            <div class="module-item">
              <span>${path.basename(f)}</span>
              <span class="dep-count">${deps.size} deps</span>
            </div>
          `;
        }).join('')}
      </div>
    `).join('')}
  </div>
</body>
</html>`;

  const outputPath = path.join(rootDir, 'ARCHITECTURE.html');
  fs.writeFileSync(outputPath, html);
  console.log(`  ${c.green}✓${c.reset} Generated responsive architecture card to: ${c.cyan}${outputPath}${c.reset}\n`);

  if (openInBrowser) {
    const platform = os.platform();
    if (platform === 'win32') {
      spawn('cmd.exe', ['/c', 'start', '""', outputPath], { detached: true });
    } else if (platform === 'darwin') {
      spawn('open', [outputPath], { detached: true });
    } else {
      spawn('xdg-open', [outputPath], { detached: true });
    }
  }
}

// CLI Execution
if (process.argv[1] && process.argv[1].endsWith('generate-diagram.js')) {
  const args = process.argv.slice(2);
  const shouldOpen = args.includes('--open') || args.includes('-o');
  const targetDir = args.find((a) => !a.startsWith('--')) || process.cwd();
  generateArchitectureDiagram(targetDir, shouldOpen);
}

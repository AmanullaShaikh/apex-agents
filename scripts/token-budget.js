#!/usr/bin/env node

import fs from 'fs';
import path from 'path';

const c = {
  reset: '\x1b[0m',
  bold: '\x1b[1m',
  dim: '\x1b[2m',
  cyan: '\x1b[36m',
  green: '\x1b[32m',
  yellow: '\x1b[33m',
  red: '\x1b[31m',
  magenta: '\x1b[35m',
  gray: '\x1b[90m'
};

const DEFAULT_IGNORED_DIRS = new Set([
  'node_modules',
  '.git',
  '.worktrees',
  'dist',
  'build',
  '.next',
  '.turbo',
  'coverage',
  '.cache'
]);

// Typical context toxic files that eat tokens without adding code intelligence
const TOXIC_PATTERNS = [
  { name: 'Package Lockfile', test: (f) => f.endsWith('package-lock.json') || f.endsWith('yarn.lock') || f.endsWith('pnpm-lock.yaml') },
  { name: 'Source Map', test: (f) => f.endsWith('.map') },
  { name: 'Minified Bundle', test: (f) => f.endsWith('.min.js') || f.endsWith('.min.css') },
  { name: 'Large SVG Asset', test: (f) => f.endsWith('.svg') },
  { name: 'Large JSON Dataset', test: (f) => f.endsWith('.json') && !f.endsWith('package.json') && !f.endsWith('tsconfig.json') },
  { name: 'Binary / Media', test: (f) => /\.(png|jpg|jpeg|gif|webp|ico|mp4|mov|wasm|pdf)$/i.test(f) }
];

function estimateTokens(text) {
  // ~3.8 chars per token is standard for code/English text in modern BPE tokenizers
  return Math.ceil(text.length / 3.8);
}

function scanBudget(dir, rootDir = dir) {
  const files = [];

  function walk(currentDir) {
    if (!fs.existsSync(currentDir)) return;
    const entries = fs.readdirSync(currentDir, { withFileTypes: true });

    for (const entry of entries) {
      if (DEFAULT_IGNORED_DIRS.has(entry.name)) continue;
      const fullPath = path.join(currentDir, entry.name);
      const relPath = path.relative(rootDir, fullPath).replace(/\\/g, '/');

      if (entry.isDirectory()) {
        walk(fullPath);
      } else if (entry.isFile()) {
        try {
          const stats = fs.statSync(fullPath);
          const sizeBytes = stats.size;
          let tokenEst = 0;
          let isToxic = false;
          let toxicReason = '';

          for (const tox of TOXIC_PATTERNS) {
            if (tox.test(relPath)) {
              isToxic = true;
              toxicReason = tox.name;
              break;
            }
          }

          // Don't read huge binary files into memory
          if (sizeBytes > 5 * 1024 * 1024) {
            tokenEst = Math.ceil(sizeBytes / 4);
          } else {
            try {
              const content = fs.readFileSync(fullPath, 'utf-8');
              tokenEst = estimateTokens(content);
            } catch {
              tokenEst = Math.ceil(sizeBytes / 4);
            }
          }

          files.push({
            relPath,
            sizeBytes,
            tokens: tokenEst,
            isToxic,
            toxicReason
          });
        } catch {
          // ignore unreadable files
        }
      }
    }
  }

  walk(dir);
  return files;
}

function formatTokens(t) {
  if (t >= 1000000) return (t / 1000000).toFixed(1) + 'M';
  if (t >= 1000) return (t / 1000).toFixed(1) + 'k';
  return t.toString();
}

function generateIgnoreFiles(cwd, toxicFiles) {
  const ignorePatterns = [
    '# Generated by Apex Agents Context Budget Optimizer',
    'package-lock.json',
    'pnpm-lock.yaml',
    'yarn.lock',
    '*.min.js',
    '*.min.css',
    '*.map',
    'dist/',
    'build/',
    'coverage/',
    '.worktrees/'
  ];

  const targets = ['.cursorignore', '.claudeignore', '.aidevignore'];
  for (const t of targets) {
    const filePath = path.join(cwd, t);
    let existing = '';
    if (fs.existsSync(filePath)) {
      existing = fs.readFileSync(filePath, 'utf-8');
    }
    const combined = Array.from(new Set([...existing.split('\n'), ...ignorePatterns])).join('\n').trim();
    fs.writeFileSync(filePath, combined + '\n');
    console.log(`  ${c.green}✓${c.reset} Generated/Updated ${c.cyan}${t}${c.reset}`);
  }
}

// CLI Execution
const args = process.argv.slice(2);
const targetDir = args.find((a) => !a.startsWith('--')) || process.cwd();
const shouldGenerate = args.includes('--generate-ignores') || args.includes('-g');

console.log(`\n${c.cyan}${c.bold}═════ APEX AGENTS CONTEXT BUDGET OPTIMIZER ═════${c.reset}`);
console.log(`Analyzing repository token weight in: ${c.cyan}${targetDir}${c.reset}...\n`);

const files = scanBudget(targetDir);
const totalTokens = files.reduce((acc, f) => acc + f.tokens, 0);
const toxicTokens = files.filter((f) => f.isToxic).reduce((acc, f) => acc + f.tokens, 0);

// Sort descending by token weight
files.sort((a, b) => b.tokens - a.tokens);

console.log(`${c.bold}CONTEXT SUMMARY:${c.reset}`);
console.log(`  • Total Files Scanned: ${c.green}${files.length}${c.reset}`);
console.log(`  • Total Estimated Tokens: ${c.cyan}${formatTokens(totalTokens)}${c.reset} tokens (~${(totalTokens * 4 / 1024).toFixed(1)} KB raw)`);
console.log(`  • Potential Toxic Bloat: ${toxicTokens > 0 ? c.red : c.green}${formatTokens(toxicTokens)}${c.reset} tokens (${((toxicTokens / (totalTokens || 1)) * 100).toFixed(1)}% of total context)`);
console.log();

console.log(`${c.bold}TOP 10 CONTEXT HEAVYWEIGHTS:${c.reset}`);
const top10 = files.slice(0, 10);
for (const file of top10) {
  const tokenStr = formatTokens(file.tokens).padStart(7);
  const tag = file.isToxic ? ` ${c.red}[${file.toxicReason}]${c.reset}` : '';
  console.log(`  ${c.yellow}${tokenStr} tokens${c.reset}  ${file.relPath}${tag}`);
}
console.log();

if (toxicTokens > 0) {
  console.log(`${c.yellow}${c.bold}⚠️ CONTEXT OPTIMIZATION RECOMMENDATION:${c.reset}`);
  console.log(`  You can save up to ${c.green}${formatTokens(toxicTokens)} tokens${c.reset} per LLM prompt by excluding lockfiles, source maps, and media.`);
  
  if (shouldGenerate) {
    console.log(`\nGenerating AI ignore files...`);
    generateIgnoreFiles(targetDir, files.filter((f) => f.isToxic));
    console.log(`\n${c.green}${c.bold}✓ Context protection active across Cursor, Claude Code, and Aider!${c.reset}\n`);
  } else {
    console.log(`  Run ${c.cyan}npx apex-agents budget --generate-ignores${c.reset} to automatically configure .cursorignore and .claudeignore!\n`);
  }
} else {
  console.log(`  ${c.green}✓ Clean context! No obvious token bloat detected.${c.reset}\n`);
}
